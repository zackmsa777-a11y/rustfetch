pub fn get_logo(
    name: &str,
    no_color: bool,
    color_override: Option<&str>,
) -> (Vec<String>, &'static str) {
    let r = if no_color { "" } else { "\x1b[0m" };

    let (art, default_col): (&[&str], &'static str) = match name.to_lowercase().as_str() {
        "ubuntu" => (UBUNTU_LOGO, "\x1b[1;31m"),
        "debian" => (DEBIAN_LOGO, "\x1b[1;31m"),
        "arch" | "archlinux" | "archarm" => (ARCH_LOGO, "\x1b[1;36m"),
        "fedora" => (FEDORA_LOGO, "\x1b[1;34m"),
        "nixos" => (NIXOS_LOGO, "\x1b[1;36m"),
        "alpine" => (ALPINE_LOGO, "\x1b[1;34m"),
        "void" => (VOID_LOGO, "\x1b[1;32m"),
        "gentoo" => (GENTOO_LOGO, "\x1b[1;35m"),
        "mint" | "linuxmint" => (MINT_LOGO, "\x1b[1;32m"),
        "manjaro" => (MANJARO_LOGO, "\x1b[1;32m"),
        "pop" | "pop_os" | "popos" => (POP_LOGO, "\x1b[1;36m"),
        "opensuse" | "suse" | "opensuse-tumbleweed" | "opensuse-leap" => {
            (OPENSUSE_LOGO, "\x1b[1;32m")
        }
        "kali" => (KALI_LOGO, "\x1b[1;34m"),
        "redhat" | "rhel" | "centos" | "rocky" | "almalinux" => (REDHAT_LOGO, "\x1b[1;31m"),
        "slackware" => (SLACKWARE_LOGO, "\x1b[1;34m"),
        "endeavouros" => (ENDEAVOUROS_LOGO, "\x1b[1;35m"),
        "freebsd" => (FREEBSD_LOGO, "\x1b[1;31m"),
        "macos" | "darwin" | "apple" => (MACOS_LOGO, "\x1b[1;37m"),
        "windows" | "win" => (WINDOWS_LOGO, "\x1b[1;36m"),
        "android" => (ANDROID_LOGO, "\x1b[1;32m"),
        "rust" | "ferris" => (RUST_LOGO, "\x1b[1;31m"),
        _ => (LINUX_LOGO, "\x1b[1;33m"),
    };

    let col = if no_color {
        ""
    } else if let Some(override_c) = color_override {
        match override_c.to_lowercase().as_str() {
            "black" => "\x1b[1;30m",
            "red" => "\x1b[1;31m",
            "green" => "\x1b[1;32m",
            "yellow" => "\x1b[1;33m",
            "blue" => "\x1b[1;34m",
            "magenta" | "purple" => "\x1b[1;35m",
            "cyan" => "\x1b[1;36m",
            "white" => "\x1b[1;37m",
            _ => default_col,
        }
    } else {
        default_col
    };

    let lines = art
        .iter()
        .map(|line| {
            if no_color {
                line.to_string()
            } else {
                format!("{col}{line}{r}")
            }
        })
        .collect();

    (lines, default_col)
}
