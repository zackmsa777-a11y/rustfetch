/// Query fastfetch dynamically if installed and an unrecognized logo is requested.
fn query_fastfetch_logo(name: &str) -> Option<Vec<String>> {
    let output = std::process::Command::new("fastfetch")
        .args([
            "--pipe",
            "true",
            "--logo",
            name,
            "-s",
            "Break",
            "--logo-padding-right",
            "0",
        ])
        .output()
        .ok()?;
    if output.status.success() {
        let text = String::from_utf8_lossy(&output.stdout);
        let mut lines: Vec<String> = text.lines().map(|l| l.trim_end().to_string()).collect();
        while lines.first().is_some_and(|l| l.trim().is_empty()) {
            lines.remove(0);
        }
        while lines.last().is_some_and(|l| l.trim().is_empty()) {
            lines.pop();
        }
        if !lines.is_empty() {
            return Some(lines);
        }
    }
    None
}

#[allow(dead_code)]
pub fn get_logo(
    name: &str,
    no_color: bool,
    color_override: Option<&str>,
) -> (Vec<String>, &'static str) {
    let r = if no_color { "" } else { "\x1b[0m" };
    let norm = name.trim().to_lowercase();

    let is_known = ALL_LOGOS.iter().any(|&l| l == norm)
        || matches!(
            norm.as_str(),
            "archlinux"
                | "archarm"
                | "pop_os"
                | "popos"
                | "suse"
                | "opensuse-tumbleweed"
                | "opensuse-leap"
                | "rhel"
                | "rockylinux"
                | "alma"
                | "ol"
                | "raspbian"
                | "parrotos"
                | "dragonflybsd"
                | "sunos"
                | "illumos"
                | "darwin"
                | "apple"
                | "win"
                | "bedrocklinux"
                | "cachy"
                | "elementaryos"
                | "mxlinux"
                | "ferris"
                | "linuxmint"
        );

    let (art_lines, default_col): (Vec<String>, &'static str) = if is_known || norm == "linux" {
        let (art, col) = logo_art(&norm);
        (art.iter().map(|s| s.to_string()).collect(), col)
    } else if let Some(ff_lines) = query_fastfetch_logo(&norm) {
        (ff_lines, "\x1b[1;36m")
    } else {
        let (art, col) = logo_art(&norm);
        (art.iter().map(|s| s.to_string()).collect(), col)
    };

    let col = if no_color {
        ""
    } else if let Some(override_c) = color_override {
        match override_c.to_lowercase().as_str() {
            "black" => "\x1b[1;30m",
            "red" => "\x1b[1;31m",
            "green" => "\x1b[1;32m",
            "yellow" => "\x1b[1;33m",
            "blue" => "\x1b[1;34m",
            "magenta" | "purple" => "\x1b[1;35m",
            "cyan" => "\x1b[1;36m",
            "white" => "\x1b[1;37m",
            _ => default_col,
        }
    } else {
        default_col
    };

    let lines = art_lines
        .into_iter()
        .map(|line| {
            if no_color {
                line
            } else {
                format!("{col}{line}{r}")
            }
        })
        .collect();

    (lines, default_col)
}

